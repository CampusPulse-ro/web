/**
 * Generates src/design/tokens.css (Tailwind's `@theme` block) from design/tokens.json, the one
 * source of CampusPulse's design tokens (docs/design-system.md). Run `bun run design:tokens`
 * after changing tokens.json; CI regenerates it and fails on any difference.
 *
 * What goes into `@theme`:
 * - `color.*` as `--color-<name>` (`bg-page`, `text-ink-muted`, `border-line`, …);
 * - `radius.*` as `--radius-<name>`, with `pill` as Tailwind's `full`, so `rounded-md` is
 *   `radius.md` (12px) here as on mobile;
 * - `font.sans` as `--font-sans`, the font of the whole page;
 * - `type.*` as `--text-<name>` with its line height, weight and letter spacing, so `text-body`
 *   is the whole `body` style.
 * Spacing stays Tailwind's: its 4px steps already hold every `space.*` value.
 */
type Group = Record<string, unknown> & { $type?: string; $description?: string }
type Token = { $value: unknown; $description?: string }
type Typography = {
  fontFamily: unknown
  fontSize: string
  fontWeight: number | string
  lineHeight: number
  letterSpacing?: string
}

const source = 'design/tokens.json'
const target = 'src/design/tokens.css'

const tokens = (await Bun.file(source).json()) as Record<string, Group>

/** The group's tokens in file order, skipping `$type`/`$description` and other `$` keys. */
function entries(group: Group): [string, Token][] {
  return Object.entries(group).filter(([name]) => !name.startsWith('$')) as [string, Token][]
}

function group(name: string, type: string): [string, Token][] {
  const g = tokens[name]
  if (!g || g.$type !== type) throw new Error(`${source}: no "${name}" group of $type ${type}`)
  return entries(g)
}

/** A DTCG alias (`{color.page}`) is replaced by the value it points at, recursively. */
function resolve(value: unknown, where: string, seen: string[] = []): unknown {
  if (typeof value === 'string') {
    const alias = /^\{([^{}]+)\}$/.exec(value)
    if (!alias) return value
    const path = alias[1]
    if (seen.includes(path))
      throw new Error(`${source}: ${where}: alias loop ${[...seen, path].join(' -> ')}`)
    const [groupName, ...rest] = path.split('.')
    const token = tokens[groupName]?.[rest.join('.')] as Token | undefined
    if (!token || !('$value' in token)) throw new Error(`${source}: ${where}: no token ${path}`)
    return resolve(token.$value, where, [...seen, path])
  }
  if (value && typeof value === 'object' && !Array.isArray(value)) {
    return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, resolve(v, where, seen)]))
  }
  return value
}

function px(value: unknown, where: string): number {
  const match = typeof value === 'string' ? /^(-?\d+(?:\.\d+)?)px$/.exec(value) : null
  if (!match) throw new Error(`${source}: ${where} is not a px value: ${String(value)}`)
  return Number(match[1])
}

/** Font sizes in rem, as Tailwind's own scale, so they follow the browser's font-size setting. */
function rem(pixels: number): string {
  return `${Number((pixels / 16).toFixed(4))}rem`
}

function fontStack(value: unknown, where: string): string {
  const families = Array.isArray(value) ? value : [value]
  return families
    .map((family) => {
      if (typeof family !== 'string') throw new Error(`${source}: ${where}: not a font name`)
      return /^[a-z-]+$/i.test(family) ? family : `'${family}'`
    })
    .join(', ')
}

const colors = group('color', 'color').map(([name, token]) => {
  const value = resolve(token.$value, `color.${name}`)
  if (typeof value !== 'string' || !/^#[0-9a-f]{6}([0-9a-f]{2})?$/i.test(value)) {
    throw new Error(`${source}: color.${name} is not a hex color: ${String(value)}`)
  }
  return `  --color-${name}: ${value};`
})

const radii = group('radius', 'dimension').map(([name, token]) => {
  const tailwindName = name === 'pill' ? 'full' : name
  return `  --radius-${tailwindName}: ${px(resolve(token.$value, `radius.${name}`), `radius.${name}`)}px;`
})

const fonts = group('font', 'fontFamily').map(
  ([name, token]) =>
    `  --font-${name}: ${fontStack(resolve(token.$value, `font.${name}`), `font.${name}`)};`,
)

const text = group('type', 'typography').flatMap(([name, token]) => {
  const where = `type.${name}`
  const t = resolve(token.$value, where) as Typography
  if (typeof t.lineHeight !== 'number')
    throw new Error(`${source}: ${where}.lineHeight must be a ratio`)
  return [
    `  --text-${name}: ${rem(px(t.fontSize, `${where}.fontSize`))};`,
    `  --text-${name}--line-height: ${t.lineHeight};`,
    `  --text-${name}--font-weight: ${t.fontWeight};`,
    `  --text-${name}--letter-spacing: ${px(t.letterSpacing ?? '0px', `${where}.letterSpacing`)}px;`,
  ]
})

const lines = [
  `/* Generated by \`bun run design:tokens\` from ${source}. Do not edit: change the JSON. */`,
  '@theme {',
  ...colors,
  ...radii,
  ...fonts,
  ...text,
  '}',
  '',
]

await Bun.write(target, lines.join('\n'))
console.log(
  `${target} <- ${source} (${colors.length} colors, ${radii.length} radii, ${fonts.length} fonts, ${text.length / 4} text styles)`,
)
